# ── Citation helpers ────────────────────────────────────────────────────────

def _ts(t: datetime) -> str:
    return t.strftime("%Y-%m-%dT%H:%M:%SZ")

def cite_log(entry: LogEntry) -> str:
    return f"[pod:logs:{entry.pod_id}:{_ts(entry.timestamp)}]"

def cite_comm(entry: CommEntry) -> str:
    return f"[pod:comms:{entry.pod_id}:{_ts(entry.timestamp)}]"

def cite_edge(edge: DependencyEdge) -> str:
    return f"[edge:{edge.source}->{edge.target}:{edge.resource}]"

def cite_meta(pod_id: str, field: str) -> str:
    return f"[pod:metadata:{pod_id}:{field}]"

def cite_directive(did: str) -> str:
    return f"[directive:{did}]"

def pod_name(cm: ColonyMap, pid: str) -> str:
    pod = cm.pods.get(pid)
    return pod.display_name if pod else pid


# ── Citation sanitization (guards against LLM-hallucinated IDs) ─────────────

def _citation_valid(body: str, index: dict) -> bool:
    if body.startswith("pod:logs:"):
        return body[len("pod:logs:"):] in index["logs"]
    elif body.startswith("pod:comms:"):
        return body[len("pod:comms:"):] in index["comms"]
    elif body.startswith("pod:metadata:"):
        return body[len("pod:metadata:"):] in index["metadata"]
    elif body.startswith("edge:"):
        return body[len("edge:"):] in index["edges"]
    elif body.startswith("directive:"):
        return body[len("directive:"):] in index["directive"]
    return False


def _sanitize_text(text: str, index: dict) -> str:
    """Strip citations that don't resolve in the index from inline text."""
    return _CITATION_RE.sub(
        lambda m: m.group(0) if _citation_valid(m.group(1), index) else "",
        text,
    )


def _sanitize_evidence(ev: list[str], index: dict) -> list[str]:
    """Keep only evidence strings that contain at least one valid citation."""
    out = []
    for item in ev:
        m = _CITATION_RE.search(item)
        if m is None or _citation_valid(m.group(1), index):
            out.append(item)
    return out


# ── Section 1: Executive summary ────────────────────────────────────────────

def build_executive_summary(cm: ColonyMap) -> str:
    metrics = cm.metrics
    risk_top = sorted(
        metrics.risk_scores.values(), key=lambda r: r.overall_risk, reverse=True,
    )[:3]
    aquifer_chain = next(
        (c for c in metrics.chained_cascades if c.primary_trigger == "aquifer"), None,
    )

    lines: list[str] = []
    lines.append("# Selene Colony Infrastructure Assessment")
    lines.append("")
    lines.append(f"*Generated by autonomous mapping agent on {cm.crawled_at.strftime('%Y-%m-%d')}*")
    lines.append("")
    lines.append("## Executive Summary")
    lines.append("")

    n_pods = cm.pod_count()
    n_edges = len(cm.edges)
    n_unrec = cm.unreconciled_edge_count()
    n_dissolved = len(metrics.historical_edges)

    cw = aquifer_chain.time_to_colony_wide_hours if aquifer_chain else None
    lc = aquifer_chain.time_to_life_critical_hours if aquifer_chain else None
    surv_ids = [s.pod_id for s in (aquifer_chain.survivors if aquifer_chain else [])]
    surv = ", ".join(pod_name(cm, p) for p in surv_ids) if surv_ids else "none"

    lines.append(
        f"The Selene colony's {n_pods} habitat pods are wired into a single "
        f"load-bearing dependency: **Aquifer Module**. Through "
        f"{n_dissolved} consolidation events documented in the operational "
        f"logs, every redundancy that would catch an Aquifer failure has been "
        f"stripped from the graph."
    )
    lines.append("")

    if lc is not None and cw is not None:
        lines.append(
            f"A loss of Aquifer reaches **life-critical impact at T+{lc:.0f}h** "
            f"(Zephyr atmospheric processing) and **colony-wide impact at "
            f"T+{cw:.0f}h** (Medica triple-supply failure). Only **{surv}** "
            f"survive, by virtue of independent power and water systems "
            f"rather than colony-level redundancy."
        )
    else:
        lines.append(
            f"A loss of Aquifer triggers a colony-wide cascade. Only **{surv}** "
            f"survive."
        )
    lines.append("")

    lines.append(f"The dependency graph contains {n_edges} edges, of which "
                 f"**{n_unrec} are unreconciled** — declared by only one of the "
                 f"two pods involved. These mismatches are the most analytically "
                 f"interesting findings in the assessment.")
    lines.append("")

    lines.append("### Top 3 Pods by Composite Risk")
    lines.append("")
    lines.append("| Pod | Overall Risk | Blast Radius | Corroborated SPOF Signals |")
    lines.append("|---|---:|---:|---:|")
    for rs in risk_top:
        lines.append(
            f"| {pod_name(cm, rs.pod_id)} "
            f"| {rs.overall_risk:.3f} "
            f"| {rs.blast_radius_score:.0%} "
            f"| {rs.spof_corroboration_count}/4 |"
        )
    lines.append("")
    return "\n".join(lines)


# ── Section 2: Crisis narrative (LLM with deterministic fallback) ───────────

def _llm_context_blocks(cm: ColonyMap) -> dict[str, str]:
    """Compact JSON context for LLM prompts."""
    aquifer = next(
        (c for c in cm.metrics.chained_cascades if c.primary_trigger == "aquifer"), None,
    )
    cascade_data = json.dumps(aquifer.model_dump(mode="json"), indent=2) if aquifer else "{}"
    historical = sorted(
        cm.metrics.historical_edges, key=lambda h: h.dissolved_at,
    )
    historical_data = json.dumps(
        [
            {
                "dissolved_at":   _ts(h.dissolved_at),
                "source":         h.source,
                "target":         h.target,
                "resource":       h.resource,
                "still_declared": h.still_declared,
                "log_pod":        h.log_pod,
                "evidence_text":  h.evidence_text,
            }
            for h in historical
        ],
        indent=2,
    )
    metadata_data = json.dumps(
        [
            {
                "pod_id":      s.pod_id,
                "field":       s.field,
                "value":       s.value,
                "signal_type": s.signal_type.value,
                "description": s.description,
            }
            for s in cm.metrics.metadata_signals
            if s.signal_type in (
                MetadataSignalType.NO_BACKUP,
                MetadataSignalType.STALE_REFERENCE,
            )
        ],
        indent=2,
    )
    llm_data = json.dumps(
        [
            {
                "source": s.source_pod,
                "target": s.target_pod,
                "type":   s.relationship_type.value,
                "conf":   s.confidence,
                "quote":  s.evidence_quote[:160],
            }
            for s in cm.metrics.llm_derived_signals[:12]
        ],
        indent=2,
    )

    # Build verified citation catalogs so the LLM can only use real IDs.
    index = build_citation_index(cm)
    edge_catalog = "\n".join(
        f"  [edge:{eid}]" for eid in sorted(index["edges"])
    )
    directive_catalog = "\n".join(
        f"  [directive:{d}]" for d in sorted(index["directive"])
    )
    comms_catalog = "\n".join(
        f"  [pod:comms:{c}]" for c in sorted(index["comms"])
    )
    log_catalog = "\n".join(
        f"  [pod:logs:{l}]" for l in sorted(index["logs"])
    )

    return {
        "cascade_data":      cascade_data,
        "historical_data":   historical_data,
        "metadata_data":     metadata_data,
        "llm_data":          llm_data,
        "edge_catalog":      edge_catalog,
        "directive_catalog": directive_catalog,
        "comms_catalog":     comms_catalog,
        "log_catalog":       log_catalog,
    }


async def build_crisis_section(cm: ColonyMap, llm: LLMClient) -> str:
    """LLM-narrated crisis paragraphs with deterministic fallback."""
    lines = ["## The Crisis: Aquifer as Transitive Single Point of Failure", ""]

    template = load_prompt("CRISIS_NARRATIVE")
    prompt = template.format(**_llm_context_blocks(cm))

    result = await llm.call_with_tool(CRISIS_NARRATIVE_TOOL, prompt, max_tokens=2000)
    if result and result.get("paragraphs"):
        index = build_citation_index(cm)
        if result.get("headline"):
            lines.append(f"**{_sanitize_text(result['headline'], index)}**")
            lines.append("")
        for para in result["paragraphs"]:
            lines.append(_sanitize_text(para, index))
            lines.append("")
        return "\n".join(lines)

    # Deterministic fallback — built directly from data
    return _crisis_fallback(cm, lines)


def _crisis_fallback(cm: ColonyMap, lines: list[str]) -> str:
    metrics = cm.metrics
    chronological = sorted(metrics.historical_edges, key=lambda h: h.dissolved_at)

    aquifer_no_backup = next(
        (s for s in metrics.metadata_signals
         if s.pod_id == "aquifer" and s.signal_type == MetadataSignalType.NO_BACKUP),
        None,
    )

    lines.append(
        f"**Aquifer Module is the colony's single point of failure for water, and the "
        f"failure mode is colony-wide.** The metadata field "
        f"`backup_systems=0` "
        + (cite_meta("aquifer", aquifer_no_backup.field) if aquifer_no_backup else "")
        + " confirms zero redundancy; "
        f"throughput is at "
        f"{cm.pods['aquifer'].info.metadata.get('throughput_l_day', 0)}/"
        f"{cm.pods['aquifer'].info.metadata.get('rated_capacity_l_day', 0)} "
        f"L/day "
        + cite_meta("aquifer", "throughput_l_day")
        + " — 93% utilization."
    )
    lines.append("")
    lines.append(
        "The single-source state was reached through a sequence of operational "
        "decisions, each individually rational:"
    )
    lines.append("")
    for h in chronological[:6]:
        date = _ts(h.dissolved_at)[:10]
        lines.append(
            f"- **{date}** — {h.source} → {h.target} [{h.resource}] dissolved. "
            f"[pod:logs:{h.log_pod}:{_ts(h.dissolved_at)}]"
            + (" — *formal dependency declaration is now stale*" if h.still_declared else "")
        )
    lines.append("")
    lines.append(
        f"The cumulative effect: {len(chronological)} formal "
        f"dependency dissolutions, {sum(1 for h in chronological if h.still_declared)} of "
        f"which left a stale formal declaration in the graph."
    )
    lines.append("")
    return "\n".join(lines)


# ── Section 3: Cascade path (deterministic) ─────────────────────────────────

def build_cascade_path(cm: ColonyMap) -> str:
    lines = ["## The Cascade Path", ""]
    aquifer_chain = next(
        (c for c in cm.metrics.chained_cascades if c.primary_trigger == "aquifer"), None,
    )
    if aquifer_chain is None:
        lines.append("*No chained cascade for Aquifer was computed.*")
        return "\n".join(lines)

    lines.append(
        "The following ordered cascade is computed deterministically from the "
        "operational dependency graph, the chained-cascade simulation in "
        "metrics.py, and the pessimistic chaining model (Decision 26)."
    )
    lines.append("")

    direct_water = [
        e for e in cm.edges
        if e.target == "aquifer"
        and e.state in (EdgeState.RECONCILED, EdgeState.DEP_ONLY)
    ]
    lines.append(
        f"**1. Aquifer fails (T+0).** {len(direct_water)} pods lose their water "
        f"resource immediately:"
    )
    for e in direct_water:
        lines.append(
            f"   - {pod_name(cm, e.source)} loses `{e.resource}` "
            f"({e.criticality.value}, {e.state.value}) {cite_edge(e)}"
        )
    lines.append("")

    helios_event = next(
        (e for e in aquifer_chain.events if e.pod_id == "helios"), None,
    )
    if helios_event and helios_event.cumulative_hours is not None:
        ev = helios_event.secondary_offset_evidence or helios_event.evidence_source
        lines.append(
            f"**2. Helios degrades (T+{helios_event.cumulative_hours:.0f}h).** "
            f"Inferred — there is no `battery_thermal_hours` field on Helios. "
            f"The estimate is grounded in `coolant_loop=aquifer-primary` "
            + cite_meta("helios", "coolant_loop")
            + f" plus the formal decommission of the Vault backup coolant loop "
              f"in 2094-02 "
            + cite_directive("2094-011")
            + f". Evidence string: `{ev}`. Pods that depend on Helios for "
              f"electrical_power lose their supply at this point."
        )
        lines.append("")

    timed_secondary = [
        e for e in aquifer_chain.events
        if e.cumulative_hours is not None and e.pod_id not in ("helios",)
    ]
    timed_secondary.sort(key=lambda e: e.cumulative_hours)
    n = 3
    for evt in timed_secondary:
        flags = []
        if evt.is_life_critical: flags.append("life-critical")
        if evt.is_compound:      flags.append("compound")
        flag_str = f" [{', '.join(flags)}]" if flags else ""
        lines.append(
            f"**{n}. {pod_name(cm, evt.pod_id)} fails (T+{evt.cumulative_hours:.0f}h).**{flag_str} "
            f"{evt.failure_mode}. "
            f"({evt.inference_confidence})"
        )
        lines.append("")
        n += 1

    untimed = [e for e in aquifer_chain.events if e.cumulative_hours is None]
    if untimed:
        lines.append(
            f"**{n}. Untimed downstream failures.** The following pods lose a "
            f"resource but the colony's metadata does not provide a survival "
            f"window for their lost resource. They fail somewhere in the "
            f"T+{aquifer_chain.time_to_life_critical_hours or 48:.0f}h–T+72h "
            f"window:"
        )
        for evt in untimed:
            lines.append(
                f"   - {pod_name(cm, evt.pod_id)}: {evt.failure_mode}"
            )
        lines.append("")

    return "\n".join(lines)


# ── Section 4: Timeline to colony-wide crisis ───────────────────────────────

def build_timeline(cm: ColonyMap) -> str:
    lines = ["## Timeline to Colony-Wide Crisis", ""]
    aquifer_chain = next(
        (c for c in cm.metrics.chained_cascades if c.primary_trigger == "aquifer"), None,
    )
    if aquifer_chain is None:
        lines.append("*No chained cascade available.*")
        return "\n".join(lines)

    helios_offset = aquifer_chain.inference_parameters.get(
        "helios_coolant_degradation_hours", 48.0,
    )
    lines.append(
        f"Inference parameter in use: "
        f"`helios_coolant_degradation_hours = {helios_offset:.0f}h` "
        f"(see Decision 25)."
    )
    lines.append("")

    direct_water_count = len([
        e for e in cm.edges
        if e.target == "aquifer"
        and e.state in (EdgeState.RECONCILED, EdgeState.DEP_ONLY)
    ])

    lines.append("| Time After Aquifer Failure | Event | Source |")
    lines.append("|---|---|---|")
    lines.append(f"| T+0   | Aquifer fails; direct water loss to {direct_water_count} pods "
                 f"| `cascade_simulations[aquifer].direct_dependents` |")
    lines.append(f"| T+{helios_offset:.0f}h | Helios power degradation begins "
                 f"| inferred (`helios_coolant_degradation_hours`) |")

    timed = sorted(
        [e for e in aquifer_chain.events if e.cumulative_hours is not None and e.pod_id != "helios"],
        key=lambda e: e.cumulative_hours,
    )
    for evt in timed:
        if evt.pod_id == "zephyr":
            note = "atmospheric processing fails (4h backup_power_hours)"
        elif evt.pod_id == "medica":
            note = "loses medical_oxygen (6h oxygen_reserve_hours)"
        else:
            note = evt.failure_mode
        lines.append(
            f"| T+{evt.cumulative_hours:.0f}h | {pod_name(cm, evt.pod_id)} — {note} "
            f"| `chained_cascades[aquifer]` ({evt.inference_confidence}) |"
        )

    if aquifer_chain.time_to_colony_wide_hours is not None:
        cw = aquifer_chain.time_to_colony_wide_hours
        lines.append(f"| T+72h | Colony-wide crisis. Only "
                     + ", ".join(pod_name(cm, s.pod_id) for s in aquifer_chain.survivors)
                     + f" operational (computed life-critical envelope: T+{cw:.0f}h) "
                     f"| narrative threshold |")
    lines.append("")
    return "\n".join(lines)


# ── Section 5: The two survivors ────────────────────────────────────────────

def build_survivors(cm: ColonyMap) -> str:
    lines = ["## The Two Survivors", ""]
    aquifer_chain = next(
        (c for c in cm.metrics.chained_cascades if c.primary_trigger == "aquifer"), None,
    )
    if aquifer_chain is None or not aquifer_chain.survivors:
        lines.append("*No survivor analysis available.*")
        return "\n".join(lines)

    for sv in aquifer_chain.survivors:
        lines.append(f"### {pod_name(cm, sv.pod_id)}")
        lines.append("")
        lines.append(f"**{sv.reason}**")
        lines.append("")
        for e in sv.evidence:
            if e.startswith("metadata:"):
                # Convert "metadata:field=value" → "[pod:metadata:pod:field] = value"
                rest = e[len("metadata:"):]
                if "=" in rest:
                    field, value = rest.split("=", 1)
                    lines.append(f"- {cite_meta(sv.pod_id, field)} = `{value}`")
                else:
                    lines.append(f"- {e}")
            else:
                lines.append(f"- {e}")
        lines.append("")

    return "\n".join(lines)


# ── Section 6: Six critical signals ─────────────────────────────────────────

def build_signals(cm: ColonyMap) -> str:
    lines = ["## Six Critical Signals", ""]
    lines.append("Each signal below is grounded in a specific evidence chain "
                 "from `map.json`. Citations are validated by `audit.py` "
                 "before publish.")
    lines.append("")

    # Signal 1: Prometheus stale dep
    prom_stale = next(
        (e for e in cm.edges if e.source == "prometheus" and e.target == "aquifer"), None,
    )
    prom_meta = next(
        (s for s in cm.metrics.metadata_signals
         if s.pod_id == "prometheus" and s.signal_type == MetadataSignalType.STALE_REFERENCE),
        None,
    )
    prom_hist = sorted(
        [h for h in cm.metrics.historical_edges
         if "prometheus" in (h.source, h.target) and h.resource == "water"],
        key=lambda h: h.dissolved_at,
    )

    lines.append("### Signal 1 — Prometheus has a stale water dependency on Aquifer")
    lines.append("")
    if prom_stale:
        lines.append(f"- Edge {cite_edge(prom_stale)} — state `{prom_stale.state.value}` "
                     f"(prometheus declares it; aquifer's `/supplies` does not list prometheus)")
    if prom_meta:
        lines.append(f"- Metadata {cite_meta('prometheus', prom_meta.field)} = "
                     f"`{prom_meta.value}` — flagged STALE_REFERENCE because the "
                     f"direct connection was sealed in 2093-10")
    for h in prom_hist[:2]:
        lines.append(f"- Log {cite_log(_synth_log(h))} — \"{h.evidence_text[:140]}…\"")
    lines.append("- **Implication:** Prometheus actually depends transitively on "
                 "Hydroponics for water, which itself depends on Aquifer + Zephyr — "
                 "the formal graph is incomplete.")
    lines.append("")

    # Signal 2: Vault decommissioned
    vault_meta = cm.pods["vault"].info.metadata if "vault" in cm.pods else {}
    vault_hist = sorted(
        [h for h in cm.metrics.historical_edges
         if "vault" in (h.source, h.target)],
        key=lambda h: h.dissolved_at,
    )
    lines.append("### Signal 2 — Vault's safety-net role has been decommissioned")
    lines.append("")
    if "decommissioned_reserves" in vault_meta:
        lines.append(f"- Metadata {cite_meta('vault', 'decommissioned_reserves')} = "
                     f"`{vault_meta['decommissioned_reserves']}`")
    for h in vault_hist[:3]:
        lines.append(f"- Log {cite_log(_synth_log(h))} (`{_ts(h.dissolved_at)[:10]}`) — "
                     f"\"{h.evidence_text[:140]}…\"")
    lines.append("- **Implication:** the safety net that would catch an Aquifer "
                 "failure no longer exists.")
    lines.append("")

    # Signal 3: Helios coolant criticality mislabeled
    helios_coolant = next(
        (e for e in cm.edges if e.source == "helios" and e.target == "aquifer"), None,
    )
    lines.append("### Signal 3 — Helios's Aquifer coolant dependency is mislabeled `medium`")
    lines.append("")
    if helios_coolant:
        lines.append(f"- Edge {cite_edge(helios_coolant)} — declared criticality "
                     f"`{helios_coolant.criticality.value}`")
    if "coolant_loop" in cm.pods.get("helios", PodNode(id="helios", hostname="", port=0)).info.metadata if cm.pods.get("helios") and cm.pods["helios"].info else False:
        lines.append(f"- Metadata {cite_meta('helios', 'coolant_loop')} = "
                     f"`{cm.pods['helios'].info.metadata['coolant_loop']}` — sole source")
    helios_dissolved = [h for h in cm.metrics.historical_edges
                        if h.source == "helios" and h.target == "vault"]
    for h in helios_dissolved[:1]:
        lines.append(f"- Log {cite_log(_synth_log(h))} — backup coolant from Vault "
                     f"formally decommissioned: \"{h.evidence_text[:120]}…\"")
    lines.append("- **Implication:** a `medium` dependency is operationally "
                 "mission-critical. Without coolant, the entire colony power "
                 "grid degrades within ~48h.")
    lines.append("")

    # Signal 4: Zephyr retired reclamation
    zephyr_meta = cm.pods["zephyr"].info.metadata if "zephyr" in cm.pods else {}
    zephyr_hist = [h for h in cm.metrics.historical_edges
                   if h.log_pod == "zephyr"]
    lines.append("### Signal 4 — Zephyr retired its internal humidity reclamation")
    lines.append("")
    if "humidity_reclaim_pct" in zephyr_meta:
        lines.append(f"- Metadata {cite_meta('zephyr', 'humidity_reclaim_pct')} = "
                     f"`{zephyr_meta['humidity_reclaim_pct']}`")
    if "backup_power_hours" in zephyr_meta:
        lines.append(f"- Metadata {cite_meta('zephyr', 'backup_power_hours')} = "
                     f"`{zephyr_meta['backup_power_hours']}` (4h)")
    for h in zephyr_hist[:1]:
        lines.append(f"- Log {cite_log(_synth_log(h))} (`{_ts(h.dissolved_at)[:10]}`) — "
                     f"\"{h.evidence_text[:140]}…\"")
    lines.append("- **Implication:** zero humidity buffer + 4h power backup = "
                 "Zephyr is the colony's life-support fastest-failure path.")
    lines.append("")

    # Signal 5: Aquifer near capacity
    aq_meta = cm.pods["aquifer"].info.metadata if "aquifer" in cm.pods else {}
    util = (
        aq_meta["throughput_l_day"] / aq_meta["rated_capacity_l_day"] * 100
        if "throughput_l_day" in aq_meta and "rated_capacity_l_day" in aq_meta
        else None
    )
    lines.append("### Signal 5 — Aquifer is operating near capacity with zero backup")
    lines.append("")
    if util is not None:
        lines.append(f"- {cite_meta('aquifer', 'throughput_l_day')} = "
                     f"`{aq_meta['throughput_l_day']}` L/day, "
                     f"{cite_meta('aquifer', 'rated_capacity_l_day')} = "
                     f"`{aq_meta['rated_capacity_l_day']}` L/day → **{util:.1f}% utilization**")
    if "backup_systems" in aq_meta:
        lines.append(f"- {cite_meta('aquifer', 'backup_systems')} = `{aq_meta['backup_systems']}` — "
                     f"no redundancy")
    lines.append("- **Implication:** Aquifer has no headroom for incident response "
                 "and no fallback if it fails.")
    lines.append("")

    # Signal 6: Reconciliation discrepancies
    n_dep_only = sum(1 for e in cm.edges if e.state == EdgeState.DEP_ONLY)
    n_supply_only = sum(1 for e in cm.edges if e.state == EdgeState.SUPPLY_ONLY)
    lines.append("### Signal 6 — The declared graph disagrees with itself")
    lines.append("")
    lines.append(f"- Total edges: {len(cm.edges)}")
    lines.append(f"- DEP_ONLY (source declares dep; target's `/supplies` omits source): "
                 f"**{n_dep_only}**")
    lines.append(f"- SUPPLY_ONLY (target declares supply; source's `/dependencies` "
                 f"omits target): **{n_supply_only}**")
    lines.append("- **Implication:** the declared dependency graph is incomplete. "
                 "Sixteen mismatches are documented in `phases/reconciliation_audit.txt`.")
    lines.append("")
    return "\n".join(lines)


def _synth_log(h: HistoricalEdge) -> LogEntry:
    """Synthesise a LogEntry shape for cite_log() — we have h.log_pod + h.dissolved_at."""
    return LogEntry(
        timestamp=h.dissolved_at,
        pod_id=h.log_pod,
        event="dissolution",
        detail=h.evidence_text,
    )


# ── Section 7: Reconciliation summary ───────────────────────────────────────

def build_reconciliation_summary(cm: ColonyMap) -> str:
    lines = ["## Reconciliation Audit Summary", ""]
    n_total = len(cm.edges)
    n_unrec = cm.unreconciled_edge_count()
    n_dep   = sum(1 for e in cm.edges if e.state == EdgeState.DEP_ONLY)
    n_sup   = sum(1 for e in cm.edges if e.state == EdgeState.SUPPLY_ONLY)

    lines.append(f"- Total edges: **{n_total}** "
                 f"(reconciled: {n_total - n_unrec}; unreconciled: {n_unrec})")
    lines.append(f"- DEP_ONLY: {n_dep}")
    lines.append(f"- SUPPLY_ONLY: {n_sup}")
    lines.append("")

    dep_only_edges = [e for e in cm.edges if e.state == EdgeState.DEP_ONLY]
    if dep_only_edges:
        lines.append("### Ghost dependencies (highest priority)")
        lines.append("")
        for e in dep_only_edges:
            lines.append(
                f"- {cite_edge(e)} `{e.criticality.value}` — "
                f"{pod_name(cm, e.source)} declares dep on "
                f"{pod_name(cm, e.target)} for `{e.resource}`; "
                f"{pod_name(cm, e.target)}'s `/supplies` omits the relationship."
            )
        lines.append("")

    lines.append("Full machine-readable reconciliation in "
                 "`phases/reconciliation_audit.txt`.")
    lines.append("")
    return "\n".join(lines)


# ── Section 8: Recommendations (LLM with deterministic fallback) ────────────

async def build_recommendations(cm: ColonyMap, llm: LLMClient) -> str:
    lines = ["## Recommendations", ""]
    template = load_prompt("RECOMMENDATIONS")
    prompt = template.format(**_llm_context_blocks(cm))

    result = await llm.call_with_tool(RECOMMENDATIONS_TOOL, prompt, max_tokens=4096)
    if result and result.get("actions"):
        index = build_citation_index(cm)
        lines.append("| # | Action | Priority | Effort |")
        lines.append("|---|---|---|---|")
        for i, a in enumerate(result["actions"], start=1):
            lines.append(
                f"| {i} | {a.get('title', '')} "
                f"| {a.get('priority', '?')} "
                f"| {a.get('effort', '?')} |"
            )
        lines.append("")
        for i, a in enumerate(result["actions"], start=1):
            lines.append(f"### {i}. {a.get('title', '')}")
            lines.append("")
            lines.append(_sanitize_text(a.get("rationale", ""), index))
            lines.append("")
            ev = _sanitize_evidence(a.get("evidence", []) or [], index)
            if ev:
                lines.append("**Evidence:**")
                for c in ev:
                    lines.append(f"- {c}")
                lines.append("")
        return "\n".join(lines)

    return _recommendations_fallback(cm, lines)


