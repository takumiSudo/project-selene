# ── Orchestrator ────────────────────────────────────────────────────────────

async def run(
    map_path: Path,
    output_path: Path,
    api_key: str | None,
) -> tuple[ColonyMap, dict]:
    logger.info("═" * 60)
    logger.info("  SELENE REPORTING AGENT")
    logger.info("  Map input:  %s", map_path)
    logger.info("  Output:     %s", output_path)
    logger.info("  LLM key:    %s", "configured" if api_key else "not set — using deterministic fallbacks")
    logger.info("═" * 60)

    if not map_path.exists():
        logger.error("map.json not found at %s — run run_mapping.sh first", map_path)
        sys.exit(1)

    cm = ColonyMap.model_validate_json(map_path.read_text())
    logger.info("Loaded ColonyMap: %d pods, %d edges, %d timeline events",
                cm.pod_count(), len(cm.edges), len(cm.timeline))

    llm = LLMClient(api_key)

    sections: list[str] = []

    logger.info("Section 1: executive summary")
    sections.append(build_executive_summary(cm))

    logger.info("Section 2: crisis narrative (LLM)")
    sections.append(await build_crisis_section(cm, llm))

    logger.info("Mermaid: operational dependency graph")
    sections.append("### Operational Dependency Graph\n\n" + build_mermaid_dependency_graph(cm))

    logger.info("Section 3: cascade path")
    sections.append(build_cascade_path(cm))

    logger.info("Section 4: timeline + cascade waterfall mermaid")
    sections.append(build_timeline(cm))
    sections.append("### Cascade Waterfall\n\n" + build_mermaid_cascade_waterfall(cm))

    logger.info("Section 5: survivors + survivor mermaid")
    sections.append(build_survivors(cm))
    sv_mermaid = build_mermaid_survivors(cm)
    if sv_mermaid:
        sections.append("### Survivor Resilience Map\n\n" + sv_mermaid)

    logger.info("Section 6: six critical signals")
    sections.append(build_signals(cm))

    logger.info("Section 7: reconciliation summary")
    sections.append(build_reconciliation_summary(cm))

    logger.info("Section 8: recommendations (LLM)")
    sections.append(await build_recommendations(cm, llm))

    # Citation audit must happen on the full text BEFORE rendering the appendix
    pre_appendix = "\n\n".join(sections)
    citation_summary = summarise_audit(pre_appendix, cm)
    logger.info(
        "Citation audit: %d total, %d unresolved",
        citation_summary["total_citations"],
        citation_summary["unresolved_count"],
    )
    for c in citation_summary["unresolved"][:5]:
        logger.warning("  unresolved: %s", c)

    # LLM enrichment signal audit
    import json as _json
    raw_data = _json.loads(map_path.read_text())
    llm_audit = _audit_llm_signals(raw_data)
    logger.info(
        "LLM signal audit: %d signals, %d issues (pod=%d ts=%d declared=%d)",
        llm_audit["signal_count"],
        llm_audit["issue_count"],
        llm_audit["tallies"]["bad_pod_id"],
        llm_audit["tallies"]["bad_timestamp"],
        llm_audit["tallies"]["wrong_formally_declared"],
    )

    sections.append(build_methodology_appendix(cm, citation_summary, llm_audit))

    report_text = "\n\n".join(sections) + "\n"
    output_path.write_text(report_text)
    size_kb = output_path.stat().st_size / 1024
    logger.info("report.md written — %.1f KB", size_kb)

    if DEFAULT_DELIVERABLE_DIR and DEFAULT_DELIVERABLE_DIR.is_dir():
        import shutil
        shutil.copy2(output_path, DEFAULT_DELIVERABLE_DIR / "report.md")
        logger.info("report.md duplicated → %s/report.md", DEFAULT_DELIVERABLE_DIR)

    return cm, citation_summary


if __name__ == "__main__":
    out_dir = DEFAULT_OUTPUT_DIR
    out_dir.mkdir(parents=True, exist_ok=True)
    asyncio.run(run(
        map_path=out_dir / "map.json",
        output_path=out_dir / "report.md",
        api_key=DEFAULT_LLM_API_KEY,
    ))
