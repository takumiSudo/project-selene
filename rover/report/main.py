# ── Mermaid diagrams ─────────────────────────────────────────────────────────

def build_mermaid_dependency_graph(cm: ColonyMap) -> str:
    """Operational dependency graph — RECONCILED + DEP_ONLY edges only.

    Color scheme:
        red   — primary SPOF (Aquifer)
        amber — high-criticality compound pods (Helios)
        green — survivors (Sentinel, Nexus)
        gray  — everyone else
    """
    lines: list[str] = []
    lines.append("```mermaid")
    lines.append("graph LR")
    lines.append("    classDef spof     fill:#ff6b6b,stroke:#c92a2a,color:white,font-weight:bold")
    lines.append("    classDef compound fill:#ffd43b,stroke:#fab005,color:#333")
    lines.append("    classDef survivor fill:#51cf66,stroke:#2f9e44,color:white")
    lines.append("    classDef pod      fill:#e9ecef,stroke:#868e96,color:#333")
    lines.append("    linkStyle default stroke:#868e96")
    lines.append("")

    # Node definitions (deduplicated, displayed name only)
    spofs    = {"aquifer"}
    compound = {"helios"}
    survivors = {"sentinel", "nexus"}
    for pid, pod in cm.pods.items():
        name = pod.display_name.replace(" ", "<br/>")
        node_id = pid.upper()
        lines.append(f"    {node_id}[\"{name}\"]")
    lines.append("")

    # Edges — operational only
    for e in cm.edges:
        if e.state == EdgeState.SUPPLY_ONLY:
            continue
        # Compact resource label for readability
        res = e.resource.replace("_", " ")
        if e.criticality.value in ("critical", "high"):
            line_style = "==>"  # bold for critical
        else:
            line_style = "-->"
        lines.append(f"    {e.source.upper()} {line_style}|{res}| {e.target.upper()}")
    lines.append("")

    for pid in spofs:    lines.append(f"    class {pid.upper()} spof")
    for pid in compound: lines.append(f"    class {pid.upper()} compound")
    for pid in survivors: lines.append(f"    class {pid.upper()} survivor")
    other = set(cm.pods) - spofs - compound - survivors
    for pid in other: lines.append(f"    class {pid.upper()} pod")
    lines.append("```")
    return "\n".join(lines)


def build_mermaid_cascade_waterfall(cm: ColonyMap) -> str:
    aquifer_chain = next(
        (c for c in cm.metrics.chained_cascades if c.primary_trigger == "aquifer"), None,
    )
    if aquifer_chain is None:
        return "*No chained cascade for Aquifer.*"

    lines: list[str] = []
    lines.append("```mermaid")
    lines.append("graph TD")
    lines.append("    classDef trigger  fill:#ff6b6b,stroke:#c92a2a,color:white,font-weight:bold")
    lines.append("    classDef inferred fill:#ffd43b,stroke:#fab005,color:#333")
    lines.append("    classDef life     fill:#fa5252,stroke:#c92a2a,color:white,font-weight:bold")
    lines.append("    classDef step     fill:#e9ecef,stroke:#868e96,color:#333")
    lines.append("    classDef survivor fill:#51cf66,stroke:#2f9e44,color:white")
    lines.append("")

    helios_offset = aquifer_chain.inference_parameters.get(
        "helios_coolant_degradation_hours", 48.0,
    )

    lines.append(f"    T0[\"T+0<br/>Aquifer fails\"]:::trigger")
    lines.append(f"    T48[\"T+{helios_offset:.0f}h (inferred)<br/>Helios degrades\"]:::inferred")
    lines.append(f"    T0 ==> T48")
    lines.append("")

    timed = sorted(
        [e for e in aquifer_chain.events
         if e.cumulative_hours is not None and e.pod_id != "helios"],
        key=lambda e: e.cumulative_hours,
    )
    for evt in timed:
        node = f"E_{evt.pod_id.upper()}"
        label = f"T+{evt.cumulative_hours:.0f}h<br/>{pod_name(cm, evt.pod_id)}<br/><i>{evt.lost_resource}</i>"
        lines.append(f"    {node}[\"{label}\"]")
        if evt.is_life_critical:
            lines.append(f"    class {node} life")
        else:
            lines.append(f"    class {node} step")
        lines.append(f"    T48 --> {node}")
    lines.append("")

    if aquifer_chain.survivors:
        for sv in aquifer_chain.survivors:
            node = f"S_{sv.pod_id.upper()}"
            lines.append(f"    {node}[\"{pod_name(cm, sv.pod_id)}<br/>survives\"]:::survivor")
    lines.append("```")
    return "\n".join(lines)


def build_mermaid_survivors(cm: ColonyMap) -> str:
    aquifer_chain = next(
        (c for c in cm.metrics.chained_cascades if c.primary_trigger == "aquifer"), None,
    )
    if aquifer_chain is None or not aquifer_chain.survivors:
        return ""

    lines: list[str] = []
    lines.append("```mermaid")
    lines.append("graph LR")
    lines.append("    classDef survivor fill:#51cf66,stroke:#2f9e44,color:white,font-weight:bold")
    lines.append("    classDef resource fill:#e3fafc,stroke:#15aabf,color:#0c8599")
    lines.append("")

    for sv in aquifer_chain.survivors:
        sv_name = pod_name(cm, sv.pod_id)
        sv_node = sv.pod_id.upper()
        lines.append(f"    {sv_node}([\"{sv_name}<br/>{sv.reason}\"]):::survivor")
        for i, ev in enumerate(sv.evidence):
            if ev.startswith("metadata:"):
                ev_text = ev[len("metadata:"):]
            else:
                continue
            res_node = f"{sv_node}_R{i}"
            label = ev_text[:40]
            lines.append(f"    {res_node}[\"{label}\"]:::resource")
            lines.append(f"    {sv_node} --> {res_node}")
    lines.append("```")
    return "\n".join(lines)


